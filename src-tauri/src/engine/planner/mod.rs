//! Work Planner for Clypra Real-Time Media Engine (Phase F)
//!
//! Enforces:
//! - Continuous preparation of upcoming media work before playback deadlines
//! - Priorities: Current (highest) > Next > Lookahead > Background
//! - Direction-aware prefetching (Forward, Reverse, Stationary)
//! - Stale work cancellation tagged with (project_revision, playback_generation)
//! - Explicit separation: The planner never performs GPU commands or rendering.

pub mod cache;
pub mod queue;

use super::render_plan::RenderPlan;
use super::types::MediaTime;
use serde::{Deserialize, Serialize};
use std::time::{Duration, Instant};

