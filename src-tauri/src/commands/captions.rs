/// Active transcription cancellation tokens mapped by jobId
pub static ACTIVE_CAPTION_JOBS: Lazy<Mutex<HashMap<String, CancellationToken>>> =
    Lazy::new(|| Mutex::new(HashMap::new()));

/// Cancels an active caption transcription job if running
#[tauri::command]
pub fn cancel_caption_transcription(job_id: String) -> bool {
    let mut jobs = ACTIVE_CAPTION_JOBS.lock();
    if let Some(token) = jobs.remove(&job_id) {
        token.cancel();
        log::debug!("🦀 [cancel_caption_transcription] Cancelled job: {job_id}");
        true
    } else {
        false
    }
}

/// Resolves standard whisper-rs DTW model preset for a model key.
pub fn dtw_model_preset_for_key(model_key: &str) -> Option<DtwModelPreset> {
    let clean = model_key
        .strip_prefix("ggml-")
        .unwrap_or(model_key)
        .strip_suffix(".bin")
        .unwrap_or(model_key)
        .strip_suffix(".pt")
        .unwrap_or(model_key)
        .to_ascii_lowercase();

    match clean.as_str() {
        "tiny" => Some(DtwModelPreset::Tiny),
        "tiny.en" => Some(DtwModelPreset::TinyEn),
        "base" => Some(DtwModelPreset::Base),
        "base.en" => Some(DtwModelPreset::BaseEn),
        "small" => Some(DtwModelPreset::Small),
        "small.en" => Some(DtwModelPreset::SmallEn),
        "medium" => Some(DtwModelPreset::Medium),
        "medium.en" => Some(DtwModelPreset::MediumEn),
        "large-v1" | "large_v1" => Some(DtwModelPreset::LargeV1),
        "large-v2" | "large_v2" => Some(DtwModelPreset::LargeV2),
        "large" | "large-v3" | "large_v3" => Some(DtwModelPreset::LargeV3),
        "turbo" | "large-v3-turbo" | "large_v3_turbo" => Some(DtwModelPreset::LargeV3Turbo),
        _ => None,
    }
}

/// Returns true if character is a Chinese Hanzi or Japanese Kanji/Kana.
/// Note: Korean Hangul is intentionally excluded because modern Korean orthography uses spaces between words.
pub fn is_cjk_char(c: char) -> bool {
    matches!(c,
        '\u{4E00}'..='\u{9FFF}' |   // CJK Unified Ideographs
        '\u{3400}'..='\u{4DBF}' |   // CJK Extension A
        '\u{20000}'..='\u{2A6DF}' | // CJK Extension B
        '\u{F900}'..='\u{FAFF}' |   // CJK Compatibility Ideographs
        '\u{3040}'..='\u{309F}' |   // Hiragana
        '\u{30A0}'..='\u{30FF}'     // Katakana
    )
}

/// Detects scripts that do not use inter-word spaces and are not yet supported for per-character splitting.
pub fn detect_unhandled_no_space_script(text: &str) -> Option<(&'static str, String)> {
    for c in text.chars() {
        let script = match c {
            '\u{0E00}'..='\u{0E7F}' => Some("Thai"),
            '\u{0E80}'..='\u{0EFF}' => Some("Lao"),
            '\u{1000}'..='\u{109F}' => Some("Myanmar (Burmese)"),
            '\u{1780}'..='\u{17FF}' => Some("Khmer"),
            '\u{0F00}'..='\u{0FFF}' => Some("Tibetan"),
            _ => None,
        };
        if let Some(s) = script {
            return Some((s, c.to_string()));
        }
    }
    None
}

#[derive(Clone, Debug, PartialEq)]
pub struct RawTokenInfo {
    pub bytes: Vec<u8>,
    pub t0: i64,
    pub t1: i64,
    pub t_dtw: i64,
}

#[derive(Clone, Debug)]
struct IntermediateWord {
    text: String,
    start_cs: i64,
    t1: i64,
    used_dtw: bool,
}

/// Merges token-level BPE fragments into whole words with byte-level accumulation.
pub fn merge_tokens_to_words(
    tokens: &[RawTokenInfo],
    seg_end_cs: i64,
) -> (Vec<WordTimestamp>, usize, Vec<CaptionWarning>) {
    if tokens.is_empty() {
        return (Vec::new(), 0, Vec::new());
    }

    struct TokenAccumulator {
        bytes: Vec<u8>,
        start_cs: i64,
        t1: i64,
        used_dtw: bool,
    }

    let mut groups: Vec<TokenAccumulator> = Vec::new();
    let mut current_group: Option<TokenAccumulator> = None;
    let mut warnings: Vec<CaptionWarning> = Vec::new();

    for token in tokens {
        // Strip Whisper special tokens (e.g. [_TT_xxx], <|startoftranscript|>)
        if token.bytes.starts_with(b"[_") || token.bytes.starts_with(b"<|") {
            continue;
        }
        if token.bytes.is_empty() {
            continue;
        }

        let (token_start_cs, token_used_dtw) = if token.t_dtw >= 0 {
            (token.t_dtw, true)
        } else {
            (token.t0, false)
        };

        if let Some(curr) = current_group.as_mut() {
            let first_byte = token.bytes[0];
            // If first byte is a UTF-8 continuation byte (10xxxxxx, 0x80..=0xBF),
            // it is part of a multi-byte sequence split across tokens and MUST NOT be a boundary.
            let is_continuation_byte = (first_byte & 0xC0) == 0x80;
            let is_whitespace_boundary = first_byte.is_ascii_whitespace();

            // Check if boundary involves Chinese/Japanese characters (no-space scripts handled)
            let curr_ends_cjk = std::str::from_utf8(&curr.bytes)
                .ok()
                .and_then(|s| s.chars().last())
                .map_or(false, is_cjk_char);
            let token_starts_cjk = std::str::from_utf8(&token.bytes)
                .ok()
                .and_then(|s| s.chars().next())
                .map_or(false, is_cjk_char);

            let is_new_word = !is_continuation_byte
                && (is_whitespace_boundary || curr_ends_cjk || token_starts_cjk);

            if is_new_word {
                groups.push(current_group.take().unwrap());
                current_group = Some(TokenAccumulator {
                    bytes: token.bytes.clone(),
                    start_cs: token_start_cs,
                    t1: token.t1,
                    used_dtw: token_used_dtw,
                });
            } else {
                curr.bytes.extend_from_slice(&token.bytes);
                curr.t1 = curr.t1.max(token.t1);
            }
        } else {
            current_group = Some(TokenAccumulator {
                bytes: token.bytes.clone(),
                start_cs: token_start_cs,
                t1: token.t1,
                used_dtw: token_used_dtw,
            });
        }
    }

    if let Some(curr) = current_group {
        groups.push(curr);
    }

    // 2. Unpack groups into words, splitting Chinese/Japanese per-character and filtering non-speech
    let mut intermediate: Vec<IntermediateWord> = Vec::new();

    for group in groups {
        let raw_str = String::from_utf8_lossy(&group.bytes);
        let cleaned = clean_word_text(&raw_str);
        if cleaned.is_empty() || is_non_speech_annotation(&cleaned) {
            continue;
        }

        // Check for unhandled no-space scripts (e.g. Thai, Lao, Burmese, Khmer)
        if let Some((script_name, sample)) = detect_unhandled_no_space_script(&cleaned) {
            let warn = CaptionWarning::UnsupportedScript {
                script: script_name.to_string(),
                sample,
            };
            if !warnings.contains(&warn) {
                warnings.push(warn);
            }
        }

        let has_cjk = cleaned.chars().any(is_cjk_char);

        if has_cjk {
            let mut parts: Vec<String> = Vec::new();
            let mut current_non_cjk = String::new();

            for c in cleaned.chars() {
                if is_cjk_char(c) {
                    if !current_non_cjk.is_empty() {
                        parts.push(current_non_cjk.clone());
                        current_non_cjk.clear();
                    }
                    parts.push(c.to_string());
                } else if c.is_whitespace() {
                    if !current_non_cjk.is_empty() {
                        parts.push(current_non_cjk.clone());
                        current_non_cjk.clear();
                    }
                } else {
                    current_non_cjk.push(c);
                }
            }
            if !current_non_cjk.is_empty() {
                parts.push(current_non_cjk);
            }

            let n_parts = parts.len();
            for (idx, part) in parts.into_iter().enumerate() {
                if is_non_speech_annotation(&part) {
                    continue;
                }
                let part_start_cs = if n_parts > 1 {
                    group.start_cs + ((group.t1 - group.start_cs) * (idx as i64) / (n_parts as i64))
                } else {
                    group.start_cs
                };
                intermediate.push(IntermediateWord {
                    text: part,
                    start_cs: part_start_cs,
                    t1: group.t1,
                    used_dtw: group.used_dtw,
                });
            }
        } else if cleaned.contains(' ') {
            let parts: Vec<&str> = cleaned.split_whitespace().collect();
            let n_parts = parts.len();
            for (idx, part) in parts.into_iter().enumerate() {
                if is_non_speech_annotation(part) {
                    continue;
                }
                let part_start_cs = if n_parts > 1 {
                    group.start_cs + ((group.t1 - group.start_cs) * (idx as i64) / (n_parts as i64))
                } else {
                    group.start_cs
                };
                intermediate.push(IntermediateWord {
                    text: part.to_string(),
                    start_cs: part_start_cs,
                    t1: group.t1,
                    used_dtw: group.used_dtw,
                });
            }
        } else {
            intermediate.push(IntermediateWord {
                text: cleaned,
                start_cs: group.start_cs,
                t1: group.t1,
                used_dtw: group.used_dtw,
            });
        }
    }

    // 3. Derive acoustic word ends and separate gapToNextMs
    let n_words = intermediate.len();
    let mut result: Vec<WordTimestamp> = Vec::with_capacity(n_words);
    let mut dtw_fallbacks = 0usize;

    for i in 0..n_words {
        let item = &intermediate[i];
        if !item.used_dtw {
            dtw_fallbacks += 1;
        }

        let start_cs = item.start_cs;
        let acoustic_end_cs = item.t1.max(start_cs + 1);
        let start_ms = (start_cs * 10) as u64;
        let end_ms = (acoustic_end_cs * 10) as u64;

        let gap_to_next_ms = if i + 1 < n_words {
            let next_start_ms = (intermediate[i + 1].start_cs * 10) as u64;
            next_start_ms.saturating_sub(end_ms)
        } else {
            let seg_end_ms = (seg_end_cs * 10) as u64;
            seg_end_ms.saturating_sub(end_ms)
        };

        result.push(WordTimestamp {
            word: item.text.clone(),
            start_ms,
            end_ms,
            gap_to_next_ms,
            start_ticks: whisper_centiseconds_to_ticks(start_cs),
            end_ticks: whisper_centiseconds_to_ticks(acoustic_end_cs),
        });
    }

    (result, dtw_fallbacks, warnings)
}

#[tauri::command]
pub async fn generate_auto_captions(
    app: tauri::AppHandle,
    video_path: String,
    model_size: Option<String>,
    language: Option<String>,
    job_id: Option<String>,
) -> Result<Vec<SubtitleSegment>, CaptionError> {
    let effective_job_id = job_id.unwrap_or_else(|| uuid::Uuid::new_v4().to_string());
    log::debug!(
        "🦀 [generate_auto_captions] Starting captioning (job: {}) for: {} model: {:?} language: {:?}",
        effective_job_id,
        video_path,
        model_size,
        language
    );

    let cancel_token = CancellationToken::new();
    {
        ACTIVE_CAPTION_JOBS
            .lock()
            .insert(effective_job_id.clone(), cancel_token.clone());
    }

    struct JobCleanupGuard(String);
    impl Drop for JobCleanupGuard {
        fn drop(&mut self) {
            ACTIVE_CAPTION_JOBS.lock().remove(&self.0);
        }
    }
    let _job_guard = JobCleanupGuard(effective_job_id.clone());

    if cancel_token.is_cancelled() {
        return Err(CaptionError::Cancelled);
    }

    // 1. Resolve model path from app data dir
    let app_data_dir = app
        .path()
        .app_data_dir()
        .map_err(|e| CaptionError::ModelNotFound(format!("Failed to get app data dir: {e}")))?;

    let model_key = model_size.unwrap_or_else(|| "tiny".to_string());
    let model_path = resolve_model_file_path(&app_data_dir, &model_key).ok_or_else(|| {
        CaptionError::ModelNotFound(format!(
            "Whisper model '{model_key}' not found or invalid. Please download it from Settings → Captions."
        ))
    })?;

    let model_path_str = model_path
        .to_str()
        .ok_or_else(|| {
            CaptionError::ModelNotFound("Failed to convert model path to string".to_string())
        })?
        .to_string();

    log::debug!(
        "🦀 [generate_auto_captions] Using verified model at: {}",
        model_path_str
    );

    if cancel_token.is_cancelled() {
        return Err(CaptionError::Cancelled);
    }

    // 2. Extract 16kHz Mono f32 PCM in-process via decode_audio_clip
    let clip_config = AudioClipConfig {
        id: format!("caption_extract_{}", effective_job_id),
        path: video_path.clone(),
        timeline_start_ticks: 0,
        source_start_ticks: 0,
        duration_ticks: -1, // Decode entire file
        gain: 1.0,
        fade_in_ticks: 0,
        fade_out_ticks: 0,
        track_id: None,
    };

    let decoded = decode_audio_clip(
        std::path::Path::new(&video_path),
        clip_config,
        16_000,
        1,
    )
    .await
    .map_err(|e| CaptionError::UnsupportedAudio(format!("Failed to decode audio: {e}")))?;

    if cancel_token.is_cancelled() {
        return Err(CaptionError::Cancelled);
    }

    if decoded.samples.is_empty() {
        return Err(CaptionError::UnsupportedAudio(
            "Audio extraction produced no audio samples from source.".to_string(),
        ));
    }

    // Guard: Enforce maximum duration / sample count (2.0 hours)
    if decoded.samples.len() > MAX_CAPTION_AUDIO_SAMPLES {
        return Err(CaptionError::UnsupportedAudio(format!(
            "Audio duration exceeds maximum supported caption limit of {:.1} hours ({:.1}s > {:.1}s). Please split the media clip before transcribing.",
            MAX_CAPTION_AUDIO_SECONDS / 3600.0,
            decoded.samples.len() as f64 / 16000.0,
            MAX_CAPTION_AUDIO_SECONDS
        )));
    }

    let audio_vec = decoded.samples.to_vec();
    log::debug!(
        "🦀 [generate_auto_captions] In-process decoded {} samples ({:.2}s)",
        audio_vec.len(),
        audio_vec.len() as f64 / 16000.0
    );

    if cancel_token.is_cancelled() {
        return Err(CaptionError::Cancelled);
    }

    // 3. Initialize WhisperContext & State on a blocking thread
    let lang_clone = language.clone();
    let job_id_clone = effective_job_id.clone();
    let cancel_token_inference = cancel_token.clone();
    let app_handle = app.clone();

    let segments = tokio::task::spawn_blocking(move || -> Result<Vec<SubtitleSegment>, CaptionError> {
        let mut context_params = WhisperContextParameters::default();
        if let Some(preset) = dtw_model_preset_for_key(&model_key) {
            log::debug!(
                "🦀 [generate_auto_captions] Configured DTW ModelPreset: {:?} (flash_attn=false)",
                preset
            );
            context_params.dtw_parameters.mode = DtwMode::ModelPreset {
                model_preset: preset,
            };
            context_params.flash_attn = false;
        } else {
            log::warn!(
                "🦀 [generate_auto_captions] No DTW model preset for '{}'; running without DTW",
                model_key
            );
        }

        let ctx = WhisperContext::new_with_params(&model_path_str, context_params)
            .map_err(|e| CaptionError::InferenceFailed(format!("Failed to load Whisper model: {e}")))?;

        let mut state = ctx
            .create_state()
            .map_err(|e| CaptionError::InferenceFailed(format!("Failed to create Whisper state: {e}")))?;

        let mut params = FullParams::new(SamplingStrategy::Greedy { best_of: 1 });
        params.set_token_timestamps(true);
        params.set_print_progress(false);
        params.set_print_realtime(false);
        params.set_print_timestamps(false);

        if let Some(ref lang) = lang_clone {
            if lang != "auto" && !lang.is_empty() {
                params.set_language(Some(lang.as_str()));
            } else {
                params.set_language(None);
            }
        } else {
            params.set_language(None);
        }

        // Set safe abort and progress callbacks
        let cancel_token_cb = cancel_token_inference.clone();
        params.set_abort_callback_safe(move || cancel_token_cb.is_cancelled());

        let app_handle_progress = app_handle.clone();
        let job_id_progress = job_id_clone.clone();
        params.set_progress_callback_safe(move |progress: i32| {
            let _ = app_handle_progress.emit(
                "caption_transcription_progress",
                CaptionProgressPayload {
                    job_id: job_id_progress.clone(),
                    progress,
                },
            );
        });

        // 5. Run full inference pipeline
        if let Err(e) = state.full(params, &audio_vec) {
            if cancel_token_inference.is_cancelled() {
                return Err(CaptionError::Cancelled);
            }
            return Err(CaptionError::InferenceFailed(format!("Whisper inference failed: {e}")));
        }

        if cancel_token_inference.is_cancelled() {
            return Err(CaptionError::Cancelled);
        }

        let n_segments = state.full_n_segments();
        let mut segments = Vec::with_capacity(n_segments as usize);
        let mut total_words = 0usize;
        let mut dtw_fallback_count = 0usize;

        // 6. Extract segments and perform byte-level whole-word merging
        for i in 0..n_segments {
            let seg = match state.get_segment(i) {
                Some(s) => s,
                None => continue,
            };

            let raw_text = seg.to_str_lossy().unwrap_or_default().trim().to_string();
            let text = clean_transcript_text(&raw_text);

            if text.is_empty() || is_non_speech_annotation(&text) {
                continue;
            }

            let start_cs = seg.start_timestamp();
            let end_cs = seg.end_timestamp();
            let start_ms = start_cs as u64 * 10;
            let end_ms = end_cs as u64 * 10;
            let start_ticks = whisper_centiseconds_to_ticks(start_cs);
            let end_ticks = whisper_centiseconds_to_ticks(end_cs);

            let n_tokens = seg.n_tokens();
            let mut raw_tokens = Vec::with_capacity(n_tokens as usize);

            for t in 0..n_tokens {
                let token = match seg.get_token(t) {
                    Some(tok) => tok,
                    None => continue,
                };

                let token_data = token.token_data();
                let bytes = token
                    .to_bytes()
                    .map(|b| b.to_vec())
                    .unwrap_or_else(|_| token.to_str_lossy().unwrap_or_default().as_bytes().to_vec());

                raw_tokens.push(RawTokenInfo {
                    bytes,
                    t0: token_data.t0,
                    t1: token_data.t1,
                    t_dtw: token_data.t_dtw,
                });
            }

            let (words, fallbacks, warnings) = merge_tokens_to_words(&raw_tokens, end_cs);
            if words.is_empty() {
                continue;
            }

            total_words += words.len();
            dtw_fallback_count += fallbacks;

            segments.push(SubtitleSegment {
                id: i as usize,
                text,
                start_ms,
                end_ms,
                start_ticks,
                end_ticks,
                words,
                warnings,
            });
        }

        log::debug!(
            "🦀 [generate_auto_captions] Generated {} segments, {} words (DTW fallbacks: {}/{})",
            segments.len(),
            total_words,
            dtw_fallback_count,
            total_words
        );

        Ok(segments)
    })
    .await
    .map_err(|e| CaptionError::InferenceFailed(format!("Whisper inference task panicked: {e}")))??;

    Ok(segments)
}

