/// Maximum audio duration allowed for caption extraction in seconds (2 hours).
pub const MAX_CAPTION_AUDIO_SECONDS: f64 = 7200.0;
/// Maximum audio sample count at 16,000 Hz mono PCM (115,200,000 samples).
pub const MAX_CAPTION_AUDIO_SAMPLES: usize = 16_000 * 7200;

/// Default pause release threshold in milliseconds for caption renderers.
/// If gapToNextMs exceeds this threshold, the renderer releases the active highlight
/// at (endMs + threshold) so words do not stay highlighted during pauses.
pub const PAUSE_RELEASE_THRESHOLD_MS: u64 = 250;

/// Compiled regex for Whisper special-token strings that can appear in segment/word text.
/// Matches: [_TT_NNN], [_BEG_], [_EOT_], [_SOT_], [_LANG_*], <|...|> timestamp strings
/// and any remaining [_…_] sentinel patterns.
static WHISPER_SPECIAL_TOKEN_RE: OnceLock<Regex> = OnceLock::new();

fn whisper_special_token_re() -> &'static Regex {
    WHISPER_SPECIAL_TOKEN_RE.get_or_init(|| {
        Regex::new(r"\[_[A-Z0-9_]+_\]|<\|[^|]*\|>").expect("invalid special token regex")
    })
}

/// Strip Whisper special-token strings from a text string and collapse extra whitespace.
pub fn strip_special_tokens(text: &str) -> String {
    let stripped = whisper_special_token_re().replace_all(text, "");
    let collapsed = stripped.split_whitespace().collect::<Vec<_>>().join(" ");
    collapsed.trim().to_string()
}

/// Returns true if the token or text is a non-speech sound annotation generated by Whisper
/// (e.g. `[music]`, `[MUSIC]`, `[BLANK_AUDIO]`, `(music)`, `[applause]`, `(applause)`, `[laughter]`).
pub fn is_non_speech_annotation(text: &str) -> bool {
    let t = text.trim();
    if t.is_empty() {
        return false;
    }
    let is_bracketed = (t.starts_with('[') && t.ends_with(']'))
        || (t.starts_with('(') && t.ends_with(')'));
    if !is_bracketed || t.len() < 3 {
        return false;
    }
    let inner = &t[1..t.len() - 1].trim();
    let lower = inner.to_ascii_lowercase();

    matches!(
        lower.as_str(),
        "music"
            | "applause"
            | "laughter"
            | "laughing"
            | "cheering"
            | "blank_audio"
            | "blank audio"
            | "silence"
            | "cough"
            | "coughing"
            | "sigh"
            | "sighing"
            | "throat clearing"
            | "throat-clearing"
            | "snort"
            | "gasp"
            | "screaming"
            | "groan"
            | "groaning"
            | "whispering"
            | "inspirational music"
            | "upbeat music"
            | "dramatic music"
            | "bell"
            | "chime"
            | "ding"
            | "beep"
            | "static"
    ) || lower.starts_with("music:")
        || lower.ends_with(" music")
}

/// Clean a Whisper segment string: strip special tokens and non-speech annotations.
/// Whisper's casing is authoritative; no arbitrary capitalization mutations are performed.
pub fn clean_transcript_text(text: &str) -> String {
    if is_non_speech_annotation(text) {
        return String::new();
    }
    let stripped = strip_special_tokens(text);
    if is_non_speech_annotation(&stripped) {
        return String::new();
    }
    stripped
}

/// Clean a single word: strip special tokens and verify it is not a non-speech annotation.
/// Preserves Whisper's authoritative casing.
pub fn clean_word_text(text: &str) -> String {
    if is_non_speech_annotation(text) {
        return String::new();
    }
    let stripped = strip_special_tokens(text);
    if is_non_speech_annotation(&stripped) {
        return String::new();
    }
    stripped
}

/// 1MHz microsecond ticks per second, matching `native_audio::TICKS_PER_SECOND`
/// and `native_core::contracts::DEFAULT_TIME_SCALE`.
pub const TICKS_PER_SECOND: i64 = 1_000_000;

/// Whisper timestamps are reported in centiseconds (10 ms units).
/// 1 centisecond = 10 ms = 10,000 microseconds (ticks at 1MHz).
#[inline]
pub fn whisper_centiseconds_to_ticks(centiseconds: i64) -> i64 {
    centiseconds.saturating_mul(10_000)
}

/// Convert audio sample index at 16,000 Hz to 1MHz microsecond ticks.
/// samples * 1,000,000 / 16,000 = (samples * 125) / 2
#[inline]
pub fn audio_16k_samples_to_ticks(samples: u64) -> i64 {
    let ticks = (samples as u128).saturating_mul(125) / 2;
    ticks.min(i64::MAX as u128) as i64
}

/// Convert 1MHz microsecond ticks back to 16,000 Hz sample count.
/// (ticks * 2) / 125
#[inline]
pub fn ticks_to_audio_16k_samples(ticks: i64) -> u64 {
    if ticks <= 0 {
        return 0;
    }
    ((ticks as u128).saturating_mul(2) / 125) as u64
}

/// Typed errors for caption generation pipeline
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
#[serde(tag = "type", content = "message")]
pub enum CaptionError {
    ModelNotFound(String),
    DownloadFailed(String),
    UnsupportedAudio(String),
    Cancelled,
    InferenceFailed(String),
}

impl std::fmt::Display for CaptionError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::ModelNotFound(msg) => write!(f, "Whisper model not found: {msg}"),
            Self::DownloadFailed(msg) => write!(f, "Model download failed: {msg}"),
            Self::UnsupportedAudio(msg) => write!(f, "Unsupported audio: {msg}"),
            Self::Cancelled => write!(f, "Caption transcription cancelled"),
            Self::InferenceFailed(msg) => write!(f, "Whisper inference failed: {msg}"),
        }
    }
}

impl std::error::Error for CaptionError {}

impl From<CaptionError> for String {
    fn from(err: CaptionError) -> Self {
        err.to_string()
    }
}

